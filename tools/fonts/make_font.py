#!/usr/bin/env python3
"""Turns tools/fonts/clear8.txt (the Clear font's glyphs drawn as text) into
src/engine/font_clear.cpp. Run from the repo root (on Windows: in a venv,
`python tools/fonts/make_font.py`)."""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
glyphs = {}
name = None
rows = []
for line in open(os.path.join(ROOT, 'tools', 'fonts', 'clear8.txt'), encoding='ascii'):
    line = line.rstrip('\n')
    if line.startswith('#') and name is None and not rows:
        continue
    if line.startswith('= '):
        name = line[2:]
        name = ' ' if name == 'space' else name
        rows = []
        continue
    if name is None:
        continue
    rows.append(line.ljust(8, '.')[:8])
    if len(rows) == 8:
        glyphs[name] = rows
        name = None
        rows = []


def byte(r):
    v = 0
    for i, ch in enumerate(r):
        if ch == '#':
            v |= 0x80 >> i
    return v


def emit(ch):
    rows = glyphs[ch]
    return '    {%s},  // %s' % (', '.join('0x%02X' % byte(r) for r in rows), repr(ch))


upper = [chr(c) for c in range(ord('A'), ord('Z') + 1)]
lower = [chr(c) for c in range(ord('a'), ord('z') + 1)]
text = [chr(c) for c in range(32, 64)]          # space .. '?' (glyphs 32-63)
for ch in upper + lower + text:
    assert ch in glyphs, 'missing glyph %r' % ch

out = ['// Generated by tools/fonts/make_font.py from tools/fonts/clear8.txt - edit those, not this.',
       '// The engine\'s own Clear font (drawn for the engine; nothing from the games).',
       '#include "font.h"', '', 'namespace font {', '',
       'const uint8_t kClearUpper[26][8] = {'] + [emit(c) for c in upper] + ['};', '',
       'const uint8_t kClearLower[26][8] = {'] + [emit(c) for c in lower] + ['};', '',
       'const uint8_t kClearText[32][8] = {'] + [emit(c) for c in text] + ['};', '', '} // namespace font', '']
open(os.path.join(ROOT, 'src', 'engine', 'font_clear.cpp'), 'w', encoding='ascii', newline='\n').write('\n'.join(out))
print('font_clear.cpp: %d glyphs' % (len(upper) + len(lower) + len(text)))
